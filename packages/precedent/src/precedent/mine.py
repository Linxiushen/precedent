_JIEBA = None
_JIEBA_TRIED = False


def _jieba():
    """Import jieba once, if the ``[zh]`` extra is installed.  Never required."""
    global _JIEBA, _JIEBA_TRIED
    if not _JIEBA_TRIED:
        _JIEBA_TRIED = True
        if os.environ.get("PRECEDENT_NO_JIEBA"):
            _JIEBA = None
        else:
            try:                                          # pragma: no cover - optional
                import jieba                              # type: ignore
                jieba.setLogLevel(60)
                _JIEBA = jieba
            except Exception:
                _JIEBA = None
    return _JIEBA


def segmenter_name() -> str:
    return "jieba" if _jieba() is not None else "bigram"


SEGMENTER = segmenter_name


