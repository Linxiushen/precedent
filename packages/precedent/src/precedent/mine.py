_REVERT_CMD = re.compile(
    r"(?i)(?:\A|[\n;&|]|&&|\|\|)\s*git\s+"
    r"(?:revert\b|restore\b|checkout\s+(?:--|HEAD|[0-9a-f]{7,40}\s+--)|"
    r"reset\s+--hard\b|stash\s+(?:pop|drop)\b)")
_PATH_IN_CMD = re.compile(r"[^\s\"']*/[^\s\"';|&]+")
#: ``cat > x <<'EOF' … EOF`` — the body is *data being written*, not commands.
#: Without this a test file that merely contains the string "git checkout --"
#: is mined as a revert (observed on this machine, 4 false positives).
_HEREDOC = re.compile(r"<<-?\s*(['\"]?)([A-Za-z_][A-Za-z0-9_]*)\1"
                      r"(?P<body>.*?)(?:^|\n)\s*\2(?=\s|$)", re.DOTALL)


def strip_heredocs(command: str) -> str:
    """Blank out heredoc bodies so their contents are not read as commands."""
    return _HEREDOC.sub(lambda m: m.group(0)[:m.start("body") - m.start()],
                        command or "")


@dataclass
class RevertAction:
    """A ``git revert``/``restore``/``checkout --`` that undoes an agent edit."""
    session_id: str
    line_no: int
    ts: str | None
    command: str
    source: str
    reverted_paths: list[str] = field(default_factory=list)
    undoes_agent_edit: bool = False

    def to_dict(self) -> dict:
        return {"sessionId": self.session_id, "lineNo": self.line_no, "ts": self.ts,
                "command": self.command[:160], "revertedPaths": self.reverted_paths[:5],
                "undoesAgentEdit": self.undoes_agent_edit,
                "locator": f"{os.path.basename(self.source)}:{self.line_no}"}


def _agent_written_paths(sess: SessionData) -> set[str]:
    out: set[str] = set()
    for tc in sess.tool_calls:
        if tc.name in ("Write", "Edit", "MultiEdit", "NotebookEdit"):
            inp = tc.input if isinstance(tc.input, dict) else {}
            for key in ("file_path", "notebook_path"):
                v = inp.get(key)
                if isinstance(v, str) and v:
                    out.add(v)
                    out.add(os.path.basename(v))
    return out


def detect_reverts(sess: SessionData) -> list[RevertAction]:
    """``git revert``/``restore``/``checkout --``/``reset --hard`` in this session.

    ``undoes_agent_edit`` is True when the command names a file the agent wrote
    or edited earlier in the same session — the strongest correction signal
    there is, because the user did not even have to type a sentence.

    Only the **main** transcript is read: a subagent running ``git checkout``
    is the agent tidying up after itself, not the user undoing the agent.  And
    heredoc bodies are blanked first, because a command that *writes a file
    containing* ``git checkout --`` is not a revert.
    """
    written = _agent_written_paths(sess)
    out: list[RevertAction] = []
    for tc in sorted(sess.tool_calls, key=lambda t: (t.ts or "", t.line_no)):
        if tc.name != "Bash" or tc.source != sess.path:
            continue
        inp = tc.input if isinstance(tc.input, dict) else {}
        cmd = inp.get("command")
        if not isinstance(cmd, str):
            continue
        scrubbed = strip_heredocs(cmd)
        if not _REVERT_CMD.search(scrubbed):
            continue
        cmd = scrubbed
        paths = [p for p in _PATH_IN_CMD.findall(cmd)][:8]
        hit = [p for p in paths
               if p in written or os.path.basename(p) in written]
        bare = [w for w in re.findall(r"[\w./\-]+", cmd)
                if w in written or os.path.basename(w) in written]
        out.append(RevertAction(
            session_id=sess.session_id, line_no=tc.line_no, ts=tc.ts,
            command=" ".join(cmd.split()), source=tc.source,
            reverted_paths=sorted(dict.fromkeys(hit + bare))[:5],
            undoes_agent_edit=bool(hit or bare)))
    return out


