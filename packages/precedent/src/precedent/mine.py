def _memory_texts(claude_home: str, sessions: list[SessionData]) -> list[tuple[str, str]]:
    """``(display name, normalised text)`` for every CLAUDE.md / memory / rule file."""
    from receipts.artifacts import discover_artifacts

    slugs: list[str] = []
    cwds: dict[str, str | None] = {}
    for s in sessions:
        if s.project_slug not in cwds:
            slugs.append(s.project_slug)
        if s.cwd and not cwds.get(s.project_slug):
            cwds[s.project_slug] = s.cwd
        cwds.setdefault(s.project_slug, None)
    out: list[tuple[str, str]] = []
    for art in discover_artifacts(claude_home, slugs, cwds):
        if art.kind not in ("memory", "memory_index", "claude_md", "rule"):
            continue
        text = art.content or ""
        if not text.strip():
            continue
        out.append((f"{art.name} ({art.kind})", text.lower()))
    return out


MIN_TOKENS_FOR_WRITTEN = 2


def _mark_written(topics: list[Topic], texts: list[tuple[str, str]]) -> None:
    for t in topics:
        toks = [tok for tok in t.top_tokens(6) if len(tok) >= 2]
        if len(toks) < MIN_TOKENS_FOR_WRITTEN:
            continue
        for name, body in texts:
            hit = [tok for tok in toks if tok in body]
            if len(hit) >= MIN_TOKENS_FOR_WRITTEN:
                t.written_in.append({"artifact": name, "matchedTokens": hit})


