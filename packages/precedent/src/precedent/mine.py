"""CORRECTION MINER v1 — every correction is a test.

A user correction is free, exogenous, user-labelled policy-violation data, and
the violating action is already on tape.  This module finds them.

What v1 adds over v0
--------------------
* **sentence-level detection** — a turn is split into sentences and each one is
  judged on its own, so "继续执行。还有，你能不能省着点 fable5 用量？" is mined as
  the second sentence, not as a 40-character blob, and the quote stored on the
  candidate is the sentence the user actually corrected with;
* **a question filter** — a sentence that ends in ``？``/``?`` and contains no
  imperative is a question, not a correction ("我们不是做自进化的吗？" is asking,
  "不要用 pip，好吗？" is telling);
* **lookaround guards** — 特别 / 别的 / 是不是 / 不用担心 / 不要紧 must not fire,
  because those characters live inside extremely common non-corrective words;
* **Chinese segmentation** — ``pip install precedent-cli[zh]`` brings jieba and
  the topic tokens become words; without it the tokeniser degrades to character
  bigrams, which is what v0 always did.  :data:`SEGMENTER` says which ran;
* **a revert detector** — ``git revert`` / ``git checkout --`` / ``git restore``
  / ``git reset --hard`` against a file the agent wrote earlier in the same
  session is a correction *without any words at all*, and 撤销 / 回滚 / 恢复 /
  undo / revert in a human turn is one with them;
* **repeated instructions across sessions** — a later turn that restates an
  earlier correction is mined even when it contains no correction word, because
  restating it *is* the signal (the user should not have to say 我说过 twice).

Layered heuristics, one confidence score
----------------------------------------
    (i)   a negation / imperative pattern fires in some sentence.  Strong forms
          ("不要", "别", "don't", "i said") score 0.55; soft ones ("又", "重新",
          "应该", "again") 0.30.  A revert *action* scores 0.50 on its own.
    (ii)  the turn follows an assistant ``tool_use`` (+0.25).  Those calls are
          recorded as the **violating action** the birth gate replays.
    (iii) the topic recurs in >=2 sessions (+0.20), decided after grouping.
    (iv)  the turn is accompanied by a revert of an agent edit (+0.15).
"""

