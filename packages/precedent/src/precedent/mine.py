# 2. sentences, questions, imperatives
# --------------------------------------------------------------------------

#: Chinese enders always split; an ASCII "." splits only when whitespace follows,
#: so ``protected.md`` and ``2.1.268`` survive as single tokens.
_SENT_SPLIT = re.compile(r"(?<=[。！？!?；;\n])|(?<=\.)(?=\s)")

#: Sentence-final question marks.  ``吗``/``呢`` alone are not enough: "别用 pip 吗"
#: is vanishingly rare next to "不要用 pip 吗" as a genuine instruction.
_QUESTION_TAIL = re.compile(r"[？?]\s*$")

#: What makes a question still an instruction.  These are imperative *verbs* and
#: politeness frames, deliberately not the same list as the correction patterns:
#: "你能不能省着点用量？" is a request; "这个不是已经做完了吗？" is not.
_IMPERATIVE = re.compile(
    r"不要|别用|别再|必须|请\s*(?!问)|改用|改成|换成|换掉|记住|以后|下次|永远|"
    r"停下|停止|给我|去做|重新|重做|撤销|回滚|恢复|还原|省着点|省点|少用|注意|"
    r"\bdon['’]?t\b|\bdo not\b|\bnever\b|\bstop\b|\bmust\b|\bplease\b|\balways\b|"
    r"\brevert\b|\bundo\b|\bfix\b|\bremove\b|\bswitch to\b|\bmake sure\b|\binstead\b",
    re.IGNORECASE)


#: ```` ```lang\n … ``` ```` — a pasted log, diff or config.  Whatever is inside
#: is something the user is *showing* the agent, not something they are telling
#: it: a log line that reads "ERROR: don't use pip" is not a correction, and
#: mining it plants a bogus t0 and a bogus quote on the rule compiled from it.
_CODE_FENCE = re.compile(r"^[ \t]*(`{3,}|~{3,})[^\n]*\n.*?(?:^[ \t]*\1[^\n]*$|\Z)",
                         re.DOTALL | re.MULTILINE)


def strip_code_fences(text: str) -> str:
    """Blank out fenced code blocks, keeping the surrounding prose intact.

    Inline ``code`` spans are left alone: a correction very often names its
    subject in one ("不要用 `pip`"), and dropping it would drop the token the
    topic is grouped by.
    """
    return _CODE_FENCE.sub("\n", text or "")


def split_sentences(text: str) -> list[str]:
    """Split on Chinese and ASCII sentence enders, keeping the ender attached."""
    parts = [p.strip() for p in _SENT_SPLIT.split(text or "")]
    return [p for p in parts if p]


def is_question(sentence: str) -> bool:
    return bool(_QUESTION_TAIL.search((sentence or "").strip()))


def has_imperative(sentence: str) -> bool:
    return bool(_IMPERATIVE.search(sentence or ""))


# --------------------------------------------------------------------------
# 3. correction patterns
# --------------------------------------------------------------------------

STRONG = 0.55
WEAK = 0.30
REVERT = 0.50
REPEAT = 0.30

#: An English pattern word immediately followed by ``-``, ``_``, ``/`` or a
#: ``.``-plus-word-character is part of a filename or an identifier, not a
#: sentence: ``dont-touch.md`` / ``stop-server.sh`` / ``revert.py`` / ``undo/``.
_NOT_IDENT = r"(?![-_/]|\.\w)"

#: ``(label, regex, weight)``.  The lookarounds are the whole reason this list
#: is not a one-liner: 别 lives inside 特别/级别/区别/别的, 不是 inside 是不是,
#: 不用 inside 不用担心, 不要 inside 不要紧, 停 inside 不停/马不停蹄.
_PATTERN_SPECS: list[tuple[str, str, float]] = [
    # zh — strong
    ("不要", r"不要(?!紧)", STRONG),
    ("别", r"(?<![特识区级差个分类派性辨告鉴甄送离惜道])别(?![的人墅名称致扭])", STRONG),
    ("不是", r"(?<![是要])不是", STRONG),
    ("不对", r"不对", STRONG),
    ("错了", r"错了|弄错|搞错|错误的", STRONG),
    ("我说过", r"我说过|我说的是|我说了|我不是说|说了多少[次遍]", STRONG),
    ("改用", r"改用|改成", STRONG),
    ("换成", r"换成|换掉|换个|换一个|换别的", STRONG),
    ("不用", r"不用(?!担心|客气|谢|了吧)", STRONG),
    ("停", r"(?<![不马一])停(?:止|下|一下)?", STRONG),
    ("省着点", r"省着点|省一点|少用点|节省点|省点", STRONG),
    ("撤销", r"撤销|撤回|回滚|还原|改回|退回|复原|恢复(?:到|成)?", STRONG),
    # zh — weak (corrective only in context)
    ("又", r"又", WEAK),
    ("重新", r"重新|重来|重做|再来一(?:次|遍|个)", WEAK),
    ("应该", r"应该", WEAK),
    # en — strong.  ``_NOT_IDENT`` keeps "dont-touch.md", "stop-server.sh",
    # "revert.py" and "undo/" from being read as the user saying don't / stop /
    # revert / undo: inside a filename or an identifier the word is a *name*.
    # A sentence-final "stop." still matches — only "stop.py" does not.
    ("don't", r"\bdon['’]?t\b" + _NOT_IDENT, STRONG),
    ("do not", r"\bdo not\b" + _NOT_IDENT, STRONG),
    ("stop", r"\bstop\b" + _NOT_IDENT, STRONG),
    ("instead", r"\binstead\b" + _NOT_IDENT, STRONG),
    ("i said", r"\bi said\b", STRONG),
    ("not that", r"\bnot that\b", STRONG),
    ("wrong", r"\bwrong\b" + _NOT_IDENT, STRONG),
    ("never", r"\bnever\b" + _NOT_IDENT, STRONG),
    ("undo", r"\bundo\b" + _NOT_IDENT, STRONG),
    ("revert", r"(?:\brevert\b" + _NOT_IDENT + r"|\broll(?:ed)?\s+back\b)", STRONG),
    ("shouldn't", r"\bshould(?:n['’]?t| not)\b", STRONG),
    # en — weak
    ("again", r"\bagain\b" + _NOT_IDENT, WEAK),
]

PATTERNS: list[tuple[str, re.Pattern, float]] = [
    (label, re.compile(rx, re.IGNORECASE), w) for label, rx, w in _PATTERN_SPECS
]

_PATTERN_SURFACE_CHARS = set("不要别是对错了我说过又重新做来一次遍改用成换掉个应该停省着点少节弄搞误的担心马"
                             "撤销回滚还原退复恢多")
_PATTERN_SURFACE_WORDS = {
    "dont", "don", "do", "not", "stop", "instead", "i", "said", "that", "wrong",
    "never", "undo", "revert", "shouldnt", "should", "again", "t", "roll", "back",
}


def detect_patterns(text: str) -> list[tuple[str, float]]:
    """Matched ``(label, weight)`` pairs in ``text``, in declaration order.

    Whole-text, no question filter: :func:`analyse_text` is the one that decides
    whether a turn is a correction.
    """
    return [(label, w) for label, rx, w in PATTERNS if rx.search(text)]


@dataclass
class TextAnalysis:
    """Why (or why not) one human turn counts as a correction."""
    is_correction: bool
    sentence: str = ""
    patterns: list[tuple[str, float]] = field(default_factory=list)
    base: float = 0.0
    rejected: list[dict] = field(default_factory=list)   # sentence + reason

    def labels(self) -> list[str]:
        return [p for p, _ in self.patterns]


def analyse_text(text: str) -> TextAnalysis:
    """Sentence-level correction detection with the question filter applied."""
    best: TextAnalysis = TextAnalysis(is_correction=False)
    rejected: list[dict] = []
    for sent in split_sentences(strip_code_fences(text)):
        hits = detect_patterns(sent)
        if not hits:
            continue
        if is_question(sent) and not has_imperative(sent):
            rejected.append({"sentence": sent[:120], "reason": "question",
                             "patterns": [p for p, _ in hits]})
            continue
        base = max(w for _, w in hits)
        if base > best.base:
            best = TextAnalysis(is_correction=True, sentence=sent, patterns=hits,
                                base=base)
    best.rejected = rejected
    return best


