def zh_tokens(run: str) -> list[str]:
    """Tokenise a Chinese run: jieba words when the ``[zh]`` extra is present,
    character bigrams otherwise.  Both paths are deterministic."""
    jb = _jieba()
    if jb is not None:                                    # pragma: no cover - optional
        out = []
        for w in jb.cut(run, cut_all=False):
            w = w.strip()
            if len(w) >= 2 and w not in ZH_STOP_WORDS:
                if not all(c in ZH_STOP_CHARS or c in _PATTERN_SURFACE_CHARS for c in w):
                    out.append(w)
        return out
    if len(run) == 1:
        if run not in ZH_STOP_CHARS and run not in _PATTERN_SURFACE_CHARS:
            return [run]
        return []
    out = []
    for i in range(len(run) - 1):
        bg = run[i:i + 2]
        if bg in ZH_STOP_BIGRAMS:
            continue
        if all(c in ZH_STOP_CHARS or c in _PATTERN_SURFACE_CHARS for c in bg):
            continue
        out.append(bg)
    return out


def content_tokens(text: str) -> set[str]:
    """Deterministic content-token set: lowercased latin words + Chinese tokens."""
    t = _URL.sub(" ", text or "")
    out: set[str] = set()
    for m in _LATIN.finditer(t):
        w = m.group(0).lower().strip("._-+")
        if len(w) >= 2 and w not in EN_STOP and any(c.isalpha() for c in w):
            out.add(w)
    for run in _CJK_RUN.findall(t):
        out.update(zh_tokens(run))
    return out


def jaccard(a: set[str], b: set[str]) -> float:
    if not a or not b:
        return 0.0
    inter = len(a & b)
    if not inter:
        return 0.0
    return inter / len(a | b)


