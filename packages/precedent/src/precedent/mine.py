@dataclass
class Correction:
    turn: HumanTurn
    patterns: list[tuple[str, float]]
    base: float
    follows_tool: bool
    repeated: bool = False
    tokens: set[str] = field(default_factory=set)
    sentence: str = ""
    signals: list[str] = field(default_factory=list)
    reverts: list[RevertAction] = field(default_factory=list)
    rejected_sentences: list[dict] = field(default_factory=list)

    @property
    def confidence(self) -> float:
        c = self.base
        if self.follows_tool:
            c += 0.25
        if self.repeated:
            c += 0.20
        if self.reverts:
            c += 0.15
        return round(min(1.0, c), 3)

    def quote(self, limit: int = MAX_QUOTE_CHARS) -> str:
        """The *sentence* the user corrected with, not the whole turn."""
        s = " ".join((self.sentence or self.turn.text).split())
        return s if len(s) <= limit else s[:limit] + "…"

    def to_dict(self) -> dict:
        t = self.turn
        return {
            "sessionId": t.session_id,
            "projectSlug": t.project_slug,
            "locator": t.locator(),
            "transcript": t.transcript,
            "lineNo": t.line_no,
            "turnIndex": t.index,
            "ts": t.ts,
            "quote": self.quote(),
            "turnQuote": t.quote(),
            "patterns": [p for p, _ in self.patterns],
            "signals": self.signals,
            "followsToolUse": self.follows_tool,
            "repeated": self.repeated,
            "confidence": self.confidence,
            "precedingTools": [{k: v for k, v in tool.items() if k != "input"}
                               for tool in t.preceding_tools],
            "reverts": [r.to_dict() for r in self.reverts],
            "rejectedSentences": self.rejected_sentences,
        }


@dataclass
class Topic:
    id: str
    members: list[Correction] = field(default_factory=list)
    label: str = ""
    written_in: list[dict] = field(default_factory=list)
    auto: dict | None = None            # auto-compiled candidate + gate verdict

    @property
    def sessions(self) -> list[str]:
        seen: list[str] = []
        for c in self.members:
            if c.turn.session_id not in seen:
                seen.append(c.turn.session_id)
        return seen

    @property
    def count(self) -> int:
        return len(self.members)

    @property
    def repeated(self) -> bool:
        return len(self.sessions) >= 2

    @property
    def t0(self) -> str | None:
        """The earliest correction time in the topic — the policy's birth date."""
        stamps = sorted(c.turn.ts for c in self.members if c.turn.ts)
        return stamps[0] if stamps else None

    def top_tokens(self, n: int = 8) -> list[str]:
        freq: dict[str, int] = {}
        for c in self.members:
            for tok in c.tokens:
                freq[tok] = freq.get(tok, 0) + 1
        return [tok for tok, _ in sorted(freq.items(),
                                          key=lambda kv: (-kv[1], kv[0]))[:n]]

    def preceding_tools(self) -> list[dict]:
        out: list[dict] = []
        for c in self.members:
            for tool in c.turn.preceding_tools:
                out.append(dict(tool, sessionId=c.turn.session_id,
                                locator=c.turn.locator()))
        return out

    def to_dict(self) -> dict:
        from .compile import suggest_check          # local import: avoids a cycle
        d = {
            "id": self.id,
            "label": self.label,
            "count": self.count,
            "sessions": self.sessions,
            "nSessions": len(self.sessions),
            "repeated": self.repeated,
            "t0": self.t0,
            "maxConfidence": max((c.confidence for c in self.members), default=0.0),
            "topTokens": self.top_tokens(),
            "quotes": [c.quote() for c in self.members[:5]],
            "corrections": [c.to_dict() for c in self.members],
            "precedingTools": [{k: v for k, v in t.items() if k != "input"}
                               for t in self.preceding_tools()[:10]],
            "writtenIn": self.written_in,
            "suggestedCheck": suggest_check(self),
        }
        if self.auto is not None:
            d["autoCompiled"] = self.auto
        return d


def _topic_id(first: Correction) -> str:
    key = f"{first.turn.session_id}:{first.turn.line_no}"
    return "t-" + hashlib.sha256(key.encode("utf-8")).hexdigest()[:8]


def _group(corrections: list[Correction], similarity: float) -> list[Topic]:
    """Deterministic single-link clustering by max Jaccard to any member."""
    topics: list[Topic] = []
    for c in corrections:
        best_idx, best_sim = -1, 0.0
        for i, t in enumerate(topics):
            sim = max(jaccard(c.tokens, m.tokens) for m in t.members)
            if sim >= similarity and sim > best_sim:
                best_idx, best_sim = i, sim
        if best_idx >= 0:
            topics[best_idx].members.append(c)
        else:
            topics.append(Topic(id="", members=[c]))
    for t in topics:
        t.id = _topic_id(t.members[0])
        t.label = " ".join(t.top_tokens(5)) or t.members[0].quote(40)
    return topics


