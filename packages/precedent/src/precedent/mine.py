@dataclass
class MineResult:
    claude_home: str
    generated_at: str
    project_filter: str | None
    last_n: int | None
    similarity: float
    sessions: list[SessionData] = field(default_factory=list)
    n_sessions: int = 0
    n_human_turns: int = 0
    n_skipped_expansions: int = 0
    n_questions_filtered: int = 0
    corrections: list[Correction] = field(default_factory=list)
    topics: list[Topic] = field(default_factory=list)
    reverts: list[RevertAction] = field(default_factory=list)
    turns_by_session: dict[str, list[HumanTurn]] = field(default_factory=dict)
    segmenter: str = "bigram"

    @property
    def n_corrections(self) -> int:
        return len(self.corrections)

    @property
    def pct_corrections(self) -> float:
        if not self.n_human_turns:
            return 0.0
        return round(100.0 * self.n_corrections / self.n_human_turns, 1)

    @property
    def repeated_topics(self) -> list[Topic]:
        return [t for t in self.topics if t.repeated]

    @property
    def written_but_violated(self) -> list[Topic]:
        return [t for t in self.topics if t.written_in]

    def topic(self, topic_id: str) -> Topic | None:
        tid = (topic_id or "").strip()
        for t in self.topics:
            if t.id == tid:
                return t
        m = re.fullmatch(r"[Tt](\d+)", tid)
        if m:
            i = int(m.group(1)) - 1
            ordered = self.ordered_topics()
            if 0 <= i < len(ordered):
                return ordered[i]
        return None

    def topics_for(self, spec: str) -> list[Topic]:
        """``"t-aaa,T3"`` -> the topics it names.  Raises ``KeyError`` on a miss."""
        out: list[Topic] = []
        for part in str(spec or "").replace(" ", "").split(","):
            if not part:
                continue
            t = self.topic(part)
            if t is None:
                raise KeyError(part)
            if t not in out:
                out.append(t)
        return out

    def ordered_topics(self) -> list[Topic]:
        """Most interesting first: repeated, then frequent, then confident."""
        return sorted(self.topics,
                      key=lambda t: (-int(t.repeated), -len(t.sessions), -t.count,
                                     -max((c.confidence for c in t.members), default=0.0),
                                     t.id))

    def to_dict(self) -> dict:
        from . import SCHEMA_VERSION, __version__
        ordered = self.ordered_topics()
        n_auto = len([t for t in self.topics if t.auto])
        n_pass = len([t for t in self.topics
                      if t.auto and t.auto.get("gate", {}).get("verdict") == "PASS"])
        return {
            "schemaVersion": SCHEMA_VERSION,
            "tool": {"name": "precedent", "version": __version__},
            "mine": {
                "claudeHome": self.claude_home,
                "generatedAt": self.generated_at,
                "projectFilter": self.project_filter,
                "lastN": self.last_n,
                "similarity": self.similarity,
                "segmenter": self.segmenter,
                "nSessions": self.n_sessions,
                "nHumanTurns": self.n_human_turns,
                "nSkippedExpansions": self.n_skipped_expansions,
                "nQuestionsFiltered": self.n_questions_filtered,
                "nCorrections": self.n_corrections,
                "pctCorrections": self.pct_corrections,
                "nTopics": len(self.topics),
                "nRepeatedTopics": len(self.repeated_topics),
                "nWrittenButViolated": len(self.written_but_violated),
                "nReverts": len(self.reverts),
                "nAutoCompiled": n_auto,
                "nAutoPass": n_pass,
                "readOnly": True,
            },
            "topics": [dict(t.to_dict(), index=f"T{i + 1}")
                       for i, t in enumerate(ordered)],
            "reverts": [r.to_dict() for r in self.reverts],
            "limitations": limitations(self),
        }


def limitations(result: MineResult) -> list[str]:
    lim = [
        "A correction is detected by surface pattern, never by a model. A turn "
        "that corrects the agent without any of the listed words is missed "
        "(false negative), and a turn that merely quotes one can be a false "
        "positive — the confidence score, not a boolean, is the honest output.",
        f"Chinese is tokenised with {result.segmenter}"
        + ("" if result.segmenter == "jieba" else
           " (character bigrams; `pip install precedent-cli[zh]` swaps in jieba)")
        + f"; the similarity threshold ({result.similarity}) is a tunable, not a truth.",
        "The question filter drops a sentence that ends in ？/? and carries no "
        f"imperative ({result.n_questions_filtered} dropped here). A question "
        "that is really an order phrased politely without any imperative word is "
        "therefore missed.",
        "\"Written but violated\" is substring/keyword matching against "
        "CLAUDE.md / memory / rule files. It shows the topic's words are in the "
        "file; it does not prove the file was loaded in the session where the "
        "correction happened (run `precedent scan` for that).",
        "Only the main transcript is read for human turns; a subagent has no "
        "human in it. Tool calls from subagents are still counted as recorded "
        "actions by the temporal birth gate.",
    ]
    if result.last_n or result.project_filter:
        lim.append("`--last` / `--project` narrow the session set, so every count "
                   "here is relative to the scanned sessions, not the whole machine.")
    return lim


def mine(claude_home: str, project_filter: str | None = None,
         last_n: int | None = None, similarity: float = DEFAULT_SIMILARITY,
         sessions: list[SessionData] | None = None,
         now_iso_str: str | None = None) -> MineResult:
    """Walk human turns, detect corrections, group them into topics."""
    from .state import now_iso

    home = os.path.realpath(os.path.expanduser(claude_home))
    sessions = sessions if sessions is not None else load_sessions(
        home, project_filter, last_n)
    result = MineResult(
        claude_home=home, generated_at=now_iso_str or now_iso(),
        project_filter=project_filter, last_n=last_n, similarity=similarity,
        sessions=sessions, n_sessions=len(sessions), segmenter=segmenter_name())

    corrections: list[Correction] = []
    non_corrections: list[HumanTurn] = []
    for sess in sessions:
        result.n_skipped_expansions += _count_expansions(sess)
        reverts = detect_reverts(sess)
        result.reverts.extend(reverts)
        turns = iter_human_turns(sess)
        result.turns_by_session[sess.session_id] = turns
        for turn in turns:
            result.n_human_turns += 1
            got = analyse_text(turn.text)
            result.n_questions_filtered += len(got.rejected)
            attached = _reverts_for_turn(turn, turns, reverts)
            if not got.is_correction:
                if attached:
                    # (iv) a revert of an agent edit is a correction with no words
                    corrections.append(Correction(
                        turn=turn, patterns=[("revert-action", REVERT)], base=REVERT,
                        follows_tool=bool(turn.preceding_tools),
                        tokens=content_tokens(turn.text) | {
                            os.path.basename(p) for r in attached
                            for p in r.reverted_paths},
                        sentence=turn.quote(), signals=["revert-action"],
                        reverts=attached, rejected_sentences=got.rejected))
                else:
                    non_corrections.append(turn)
                continue
            signals = ["pattern"]
            if attached:
                signals.append("revert-action")
            corrections.append(Correction(
                turn=turn, patterns=got.patterns, base=got.base,
                follows_tool=bool(turn.preceding_tools),
                tokens=content_tokens(got.sentence or turn.text),
                sentence=got.sentence, signals=signals, reverts=attached,
                rejected_sentences=got.rejected))

    # (v) repeated instructions across sessions — no correction word required
    corrections.extend(_repeat_across_sessions(corrections, non_corrections))

    corrections.sort(key=lambda c: (c.turn.ts or "", c.turn.session_id, c.turn.line_no))
    result.corrections = corrections
    result.topics = _group(corrections, similarity)

    for t in result.topics:
        if t.repeated:
            for c in t.members:
                c.repeated = True
                if "repeated-topic" not in c.signals:
                    c.signals.append("repeated-topic")

    _mark_written(result.topics, _memory_texts(home, sessions))
    return result


def _reverts_for_turn(turn: HumanTurn, turns: list[HumanTurn],
                      reverts: list[RevertAction]) -> list[RevertAction]:
    """Reverts that happened between the previous human turn and this one.

    Ordering is by timestamp, not line number: a line number is only comparable
    within one transcript file.
    """
    prev_ts = ""
    for t in turns:
        if t.line_no >= turn.line_no:
            break
        prev_ts = t.ts or prev_ts
    this_ts = turn.ts or ""
    if not this_ts:
        return []
    return [r for r in reverts
            if r.undoes_agent_edit and r.ts and prev_ts < r.ts < this_ts]


def _repeat_across_sessions(corrections: list[Correction],
                            others: list[HumanTurn]) -> list[Correction]:
    """Turns that restate an earlier correction from a *different* session.

    The user should not have to type 我说过 for the miner to notice that this is
    the third time they have asked for the same thing.
    """
    out: list[Correction] = []
    for turn in others:
        toks = content_tokens(turn.text)
        if len(toks) < MIN_REPEAT_TOKENS:
            continue
        best = None
        for c in corrections:
            if c.turn.session_id == turn.session_id:
                continue
            if (c.turn.ts or "") >= (turn.ts or ""):
                continue               # only a *later* restatement counts
            sim = jaccard(toks, c.tokens)
            if sim >= REPEAT_SIMILARITY and (best is None or sim > best[0]):
                best = (sim, c)
        if best is None:
            continue
        sim, src = best
        out.append(Correction(
            turn=turn, patterns=[("repeat-across-sessions", REPEAT)], base=REPEAT,
            follows_tool=bool(turn.preceding_tools), tokens=toks,
            sentence=turn.quote(), signals=["repeat-across-sessions"],
            rejected_sentences=[{"sentence": src.quote(60),
                                 "reason": f"restates {src.turn.session_id[:8]} "
                                           f"(jaccard {sim:.2f})",
                                 "patterns": []}]))
    return out


def _count_expansions(sess: SessionData) -> int:
    """How many user records the skip-list removed — reported, never hidden."""
    n = 0
    for _line_no, rec in iter_records(sess.path):
        if rec.get("type") != "user" or rec.get("sourceToolAssistantUUID"):
            continue
        origin = rec.get("origin")
        if isinstance(origin, dict) and origin.get("kind") and origin.get("kind") != "human":
            continue
        texts = [t for t in _text_blocks(rec) if t and t.strip()]
        if texts and is_skill_expansion("\n".join(texts).strip(), rec):
            n += 1
    return n


def write_topics(state, result: MineResult) -> str:
    """Persist the mined topics so ``precedent compile`` can address them."""
    payload = result.to_dict()
    return state.write_json(os.path.join(state.root, "topics.json"), payload)


def load_topics(state) -> dict | None:
    data = state.read_json(os.path.join(state.root, "topics.json"))
    return data if isinstance(data, dict) else None
