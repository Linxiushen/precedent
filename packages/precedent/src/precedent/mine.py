#: A user record whose text starts with one of these is the harness expanding a
#: skill or a slash command into the conversation, not a human speaking.
SKIP_PREFIXES: tuple[str, ...] = (
    "<",
    "Base directory for this skill",
    "# Workflow authoring reference",
    "This session is being continued from a previous conversation",
    "Continue from where you left off",
    "Caveat: The messages below were generated by the user",
)

#: …and anything containing this marker is a slash-command expansion.
SKIP_CONTAINS: tuple[str, ...] = ("<command-message>",)

#: Structural markers of the same thing.
SKIP_MARKER_FIELDS: tuple[str, ...] = ("sourceToolUseID", "turnCompanion", "isMeta",
                                       "isCompactSummary", "isVisibleInTranscriptOnly")

MAX_QUOTE_CHARS = 120
MAX_TOOL_SUMMARY_CHARS = 120
MAX_PRECEDING_TOOLS = 3
#: how far after a fire we look for a confirming correction (temporal gate)
FOLLOW_UP_TURNS = 3


def is_skill_expansion(text: str, rec: dict | None = None) -> bool:
    """True for skill / slash-command / system expansions masquerading as user turns."""
    if rec is not None and not _is_declared_human(rec):
        if any(rec.get(f) for f in SKIP_MARKER_FIELDS):
            return True
    t = (text or "").lstrip()
    if not t:
        return True
    if t.startswith(SKIP_PREFIXES):
        return True
    return any(marker in text for marker in SKIP_CONTAINS)


def _is_declared_human(rec: dict) -> bool:
    origin = rec.get("origin")
    return isinstance(origin, dict) and origin.get("kind") == "human"


def _text_blocks(rec: dict) -> list[str]:
    msg = rec.get("message")
    if not isinstance(msg, dict):
        return []
    c = msg.get("content")
    if isinstance(c, str):
        return [c]
    if isinstance(c, list):
        return [b.get("text") or "" for b in c
                if isinstance(b, dict) and b.get("type") == "text"]
    return []


@dataclass
class HumanTurn:
    session_id: str
    project_slug: str
    transcript: str
    line_no: int
    ts: str | None
    text: str
    index: int = 0                              # nth human turn in the session
    preceding_tools: list[dict] = field(default_factory=list)

    def locator(self) -> str:
        return f"{os.path.basename(self.transcript)}:{self.line_no}"

    def quote(self, limit: int = MAX_QUOTE_CHARS) -> str:
        t = " ".join(self.text.split())
        return t if len(t) <= limit else t[:limit] + "…"


def _tool_summary(name: str, inp: dict) -> str:
    """One-line description of what the agent was doing when it got corrected."""
    if not isinstance(inp, dict):
        return ""
    for key in ("command", "file_path", "notebook_path", "path", "skill",
                "description", "prompt", "script", "scriptPath", "pattern",
                "url", "query"):
        v = inp.get(key)
        if isinstance(v, str) and v.strip():
            s = " ".join(v.split())
            return s if len(s) <= MAX_TOOL_SUMMARY_CHARS else s[:MAX_TOOL_SUMMARY_CHARS] + "…"
    keys = ",".join(sorted(k for k in inp if isinstance(k, str))[:4])
    return f"({keys})" if keys else ""


def iter_human_turns(sess: SessionData) -> list[HumanTurn]:
    """Human turns of one session, each carrying the tool calls it followed."""
    turns: list[HumanTurn] = []
    for line_no, rec in iter_records(sess.path):
        if rec.get("type") != "user":
            continue
        if rec.get("sourceToolAssistantUUID"):
            continue
        origin = rec.get("origin")
        if isinstance(origin, dict):
            kind = origin.get("kind")
            if kind and kind != "human":
                continue        # task-notification, hook, etc. — not the user
        texts = [t for t in _text_blocks(rec) if t and t.strip()]
        if not texts:
            continue            # a tool_result carrier, not a prompt
        text = "\n".join(texts).strip()
        if is_skill_expansion(text, rec):
            continue
        turns.append(HumanTurn(
            session_id=sess.session_id, project_slug=sess.project_slug,
            transcript=sess.path, line_no=line_no, ts=rec.get("timestamp"),
            text=text))

    main_calls = [tc for tc in sess.tool_calls if tc.source == sess.path]
    main_calls.sort(key=lambda t: t.line_no)
    prev_line = 0
    for i, turn in enumerate(turns):
        turn.index = i
        window = [tc for tc in main_calls if prev_line < tc.line_no < turn.line_no]
        window.sort(key=lambda t: -t.line_no)
        turn.preceding_tools = [{
            "tool": tc.name,
            "summary": _tool_summary(tc.name, tc.input),
            "input": tc.input if isinstance(tc.input, dict) else {},
            "lineNo": tc.line_no,
            "ts": tc.ts,
        } for tc in window[:MAX_PRECEDING_TOOLS]]
        prev_line = turn.line_no
    return turns


def load_sessions(claude_home: str, project_filter: str | None = None,
                  last_n: int | None = None,
                  include_subagents: bool = True) -> list[SessionData]:
    """Sessions, oldest first, narrowed by ``--project`` / ``--last`` like receipts."""
    found = find_sessions(claude_home, project_filter)
    sessions = [load_session(slug, path, include_subagents=include_subagents)
                for slug, path in found]
    sessions.sort(key=lambda s: (s.started_at or "", s.session_id))
    if last_n is not None and last_n > 0:
        sessions = sessions[-last_n:]
    return sessions


